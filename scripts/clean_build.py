#!/usr/bin/env python3
"""Remove generated build artifacts and project-local Python caches.

Examples
--------
    .venv/bin/python scripts/clean_build.py --dry-run
    .venv/bin/python scripts/clean_build.py

``build/`` is disposable: every GDS/PNG in it is regenerated by the step
scripts.  The virtual environment and source files are never touched.
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="only print what would be removed")
    args = parser.parse_args()

    targets: list[Path] = [ROOT / "build"]
    for pattern in ("__pycache__", ".pytest_cache", ".mypy_cache"):
        for path in ROOT.rglob(pattern):
            if ".venv" in path.parts:
                continue
            targets.append(path)

    for path in targets:
        if not path.exists():
            continue
        print(("would remove " if args.dry_run else "removing ") + str(path.relative_to(ROOT)))
        if not args.dry_run:
            shutil.rmtree(path)

    print("done" + (" (dry run)" if args.dry_run else ""))


if __name__ == "__main__":
    main()
